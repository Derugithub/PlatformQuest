// Bundles the Phaser game (game/*.ts plus the shared logic in src/core) into one self-contained
// HTML page and writes it as a string module the app loads into the WebView. Fully offline:
// Phaser, the game code and the Inter font are all inlined; nothing is fetched at runtime.
//
//   npm run build:game
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/game-html/game-html.js');

/** Hash of every input, so a test can tell when the committed bundle is stale. */
export function sourceHash() {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (/\.(ts|mjs)$/.test(entry.name)) files.push(path);
    }
  };
  walk(join(root, 'game'));
  walk(join(root, 'src/core'));
  files.push(join(root, 'scripts/build-game.mjs'));
  files.sort();
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file.slice(root.length).replaceAll('\\', '/'));
    hash.update(readFileSync(file, 'utf8').replace(/\r\n/g, '\n'));
  }
  return hash.digest('hex').slice(0, 16);
}

async function main() {
  const result = await build({
    entryPoints: [join(root, 'game/main.ts')],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['chrome80'],
    write: false,
    legalComments: 'none',
    alias: { phaser: join(root, 'node_modules/phaser/dist/phaser-arcade-physics.min.js') },
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'warning',
  });
  const js = result.outputFiles[0].text;
  const font = readFileSync(join(root, 'node_modules/@expo-google-fonts/inter/700Bold/Inter_700Bold.ttf')).toString('base64');
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><title>PlatformQuest</title><style>@font-face{font-family:Inter;font-weight:700;src:url(data:font/ttf;base64,${font}) format('truetype')}html,body{margin:0;padding:0;width:100%;height:100%;overflow:hidden;background:#0f172a;touch-action:none;-webkit-tap-highlight-color:transparent;-webkit-user-select:none;user-select:none;overscroll-behavior:none}#game{position:fixed;inset:0}</style></head><body><div id="game"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
  const hash = sourceHash();
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(
    outFile,
    `// Generated by scripts/build-game.mjs. Do not edit; run \`npm run build:game\`.\n` +
      `export const GAME_SOURCE_HASH = ${JSON.stringify(hash)};\n` +
      `export const GAME_HTML = ${JSON.stringify(html)};\n`,
  );
  console.log(`game bundle: ${(html.length / 1024).toFixed(0)} KB, source hash ${hash}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
